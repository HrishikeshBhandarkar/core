package com.maxrave.kotlinytmusicscraper

import com.maxrave.kotlinytmusicscraper.utils.parseCookieString
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull
import kotlin.test.assertTrue

class CookieAuthTest {

    @Test
    fun testParseStandardCookieString() {
        val cookie = "SAPISID=test_sapisid; __Secure-3PAPISID=test_3p; SID=test_sid_with_padding=="
        val map = parseCookieString(cookie)
        assertEquals("test_sapisid", map["SAPISID"])
        assertEquals("test_3p", map["__Secure-3PAPISID"])
        assertEquals("test_sid_with_padding==", map["SID"])
    }

    @Test
    fun testParseUnspacedCookieString() {
        val cookie = "SAPISID=test_sapisid;__Secure-3PAPISID=test_3p;LOGIN_INFO=AFmmF2cwRQIhA==;"
        val map = parseCookieString(cookie)
        assertEquals("test_sapisid", map["SAPISID"])
        assertEquals("test_3p", map["__Secure-3PAPISID"])
        assertEquals("AFmmF2cwRQIhA==", map["LOGIN_INFO"])
    }

    @Test
    fun testParseNetscapeCookieFormat() {
        val netscape = """
            # Netscape HTTP Cookie File
            # http://curl.haxx.se/rfc/cookie_spec.html
            # This file was generated by libcurl! Edit at your own risk.

            .youtube.com	TRUE	/	TRUE	1799999999	SAPISID	netscape_sapisid_value
            .youtube.com	TRUE	/	TRUE	1799999999	__Secure-3PAPISID	netscape_3p_value
            .youtube.com	TRUE	/	TRUE	1799999999	SID	netscape_sid_value
        """.trimIndent()

        val map = parseCookieString(netscape)
        assertEquals("netscape_sapisid_value", map["SAPISID"])
        assertEquals("netscape_3p_value", map["__Secure-3PAPISID"])
        assertEquals("netscape_sid_value", map["SID"])
    }

    @Test
    fun testAuthorizationHeaderTimestampNot1970() {
        val ytmusic = Ytmusic()
        ytmusic.cookie = "SAPISID=my_sapisid_token; __Secure-3PAPISID=my_3p_token"

        val auth = ytmusic.getAuthorizationHeader()
        assertNotNull(auth)
        assertTrue(auth.startsWith("SAPISIDHASH "))

        val token = auth.removePrefix("SAPISIDHASH ")
        val parts = token.split("_")
        assertEquals(2, parts.size, "SAPISIDHASH should be formatted as <timestamp>_<sha1>")

        val timestamp = parts[0].toLongOrNull()
        assertNotNull(timestamp)
        // Must be in current decade (seconds > 1.7 billion), NOT in year 1970 (~1.7 million)
        assertTrue(
            timestamp > 1_700_000_000L,
            "Timestamp must be in seconds since epoch (> 1.7 billion). Got: $timestamp (if ~1.7 million, it is 1970!)"
        )
    }

    @Test
    fun testAuthorizationHeaderFallbackToOnlySapisid() {
        val ytmusic = Ytmusic()
        // Only SAPISID present, no __Secure-3PAPISID
        ytmusic.cookie = "SAPISID=my_sapisid_token"

        val auth = ytmusic.getAuthorizationHeader()
        assertNotNull(auth, "Should succeed with only SAPISID present")
        assertTrue(auth.startsWith("SAPISIDHASH "))
    }

    @Test
    fun testAuthorizationHeaderFallbackToOnlySecure3PAPISID() {
        val ytmusic = Ytmusic()
        // Only __Secure-3PAPISID present, no SAPISID
        ytmusic.cookie = "__Secure-3PAPISID=my_3p_token"

        val auth = ytmusic.getAuthorizationHeader()
        assertNotNull(auth, "Should succeed with only __Secure-3PAPISID present")
        assertTrue(auth.startsWith("SAPISIDHASH "))
    }
}
